package com.petro.smsapp.util

import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.style.TextDirection

/**
 * قانون کلی نمایش متن‌های دینامیکِ برنامه (اسم مخاطب یا شماره‌ای که به‌جای اسم نشون داده میشه):
 * جهتِ پاراگراف بر اساس محتوا تعیین بشه، نه جهتِ کلیِ صفحه (که همیشه راست‌به‌چپه، چون
 * MainActivity کل برنامه رو زیرِ LocalLayoutDirection.Rtl می‌ذاره).
 *
 * اگه اولین کاراکتر قویِ متن فارسی/عربی باشه (یعنی واقعاً اسمه) راست‌به‌چپ می‌مونه -
 * دقیقاً همون چیزی که قبلاً بود، بدون هیچ تغییر ظاهری. اگه متن فقط عدد/+/- بود (یعنی
 * جای اسم، خودِ شماره نمایش داده میشه - وقتی مخاطب تو Contacts ذخیره نشده) خودکار
 * چپ‌به‌راست میشه و دیگه برعکس (mirror) نمایش داده نمیشه.
 *
 * از این extension هرجا که قراره «اسم مخاطب یا شماره» نمایش داده بشه استفاده کن -
 * لیست مکالمات، بلاک، خصوصی، علاقه‌مندی‌ها، سطل زباله، زمان‌بندی‌شده، جزئیات پیام،
 * پیام جدید، انتخاب مخاطب و هرجای بعدی که مشابهش اضافه بشه.
 */
fun TextStyle.autoDirection(): TextStyle = this.copy(textDirection = TextDirection.ContentOrLtr)